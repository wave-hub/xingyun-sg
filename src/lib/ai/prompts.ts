// ========================================
// 用戶問題模板
// ========================================

export function buildUserMessage(
  method: 'ziwei' | 'bazi' | 'liuren' | 'combined',
  chartDataJson: string,
  userQuestion?: string
): string {
  const methodNames = {
    ziwei: '紫微斗數',
    bazi: '八字命理',
    liuren: '大六壬',
    combined: '三術合參',
  };

  let prompt = `以下是命主的${methodNames[method]}命盤數據（JSON格式），請仔細分析並提供專業解讀：

\`\`\`json
${chartDataJson}
\`\`\`

請按照你的專業框架進行完整解讀。`;

  if (userQuestion && userQuestion.trim()) {
    prompt += `\n\n命主特別想了解的問題：${userQuestion}`;
  }

  return prompt;
}
